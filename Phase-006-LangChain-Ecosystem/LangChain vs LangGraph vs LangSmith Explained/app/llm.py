"""Chat-model factory: mock, OpenAI or a local Ollama model — chosen by LLM_PROVIDER.

All three return a LangChain chat model, so the chains and the workflow do not change when
the provider changes. That interchangeability is one of LangChain's main benefits.

`MockChatModel` is a real LangChain chat model whose replies are predefined JSON. It needs no
API key and no network, always gives the same answer, and can simulate failures for tests.
Mock replies are labelled in every API response — they are never presented as live AI output.
"""
from __future__ import annotations

import json
import re
from typing import Any, Optional

from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage, BaseMessage
from langchain_core.outputs import ChatGeneration, ChatResult
from pydantic import PrivateAttr

from app.config import Settings
from app.knowledge import predefined_answer

MOCK_NOTE = "Mock mode: a predefined sample answer, not generated by a language model."


class MockChatModel(BaseChatModel):
    """Deterministic stand-in for a chat model.

    fail_times    — raise an error on the first N calls (simulates an unavailable model)
    invalid_times — return text that is not valid JSON on the first N calls (simulates bad output)
    """

    fail_times: int = 0
    invalid_times: int = 0
    _calls: int = PrivateAttr(default=0)

    @property
    def _llm_type(self) -> str:
        return "mock-tutor"

    @property
    def calls(self) -> int:
        return self._calls

    def _generate(self, messages: list[BaseMessage], stop: Optional[list[str]] = None,
                  run_manager: Any = None, **kwargs: Any) -> ChatResult:
        self._calls += 1
        if self._calls <= self.fail_times:
            raise RuntimeError("Simulated model failure (mock mode)")
        if self._calls <= self.fail_times + self.invalid_times:
            content = "Sorry, I cannot answer in JSON right now."
        else:
            content = json.dumps(self._reply(messages))
        return ChatResult(generations=[ChatGeneration(message=AIMessage(content=content))])

    @staticmethod
    def _reply(messages: list[BaseMessage]) -> dict:
        system = " ".join(str(m.content) for m in messages if m.type == "system")
        human = " ".join(str(m.content) for m in messages if m.type == "human")
        match = re.search(r"^Topic:\s*(.+)$", human, re.M)
        answer = predefined_answer(match.group(1).strip() if match else "General question")
        if "TASK=example" in system:
            return {"example": answer["example"]}
        if "TASK=explain" in system:
            return {k: answer[k] for k in ("topic", "explanation", "key_points")}
        return {k: answer[k] for k in ("topic", "explanation", "example")}


def get_chat_model(settings: Settings) -> BaseChatModel:
    """Build the chat model for the configured provider (call provider_problem() first)."""
    if settings.llm_provider == "openai":
        from langchain_openai import ChatOpenAI
        return ChatOpenAI(model=settings.openai_model, temperature=settings.temperature,
                          timeout=settings.timeout_seconds, max_retries=1)
    if settings.llm_provider == "ollama":
        from langchain_ollama import ChatOllama
        return ChatOllama(model=settings.ollama_model, base_url=settings.ollama_base_url,
                          temperature=settings.temperature, format="json")
    return MockChatModel()
