"""Real-model integration tests — a local Ollama model, no mocks.

They are excluded from the default offline run. Run them with:

    ollama pull qwen2.5:0.5b
    python -m pytest -m ollama

Each test is skipped (not failed) when the Ollama server or the model is not available.
A small local model's wording varies, so the checks focus on what the code guarantees:
real generation (mode "ollama", no mock note, not a predefined answer), valid structure,
and a workflow that always terminates.
"""
import os

import httpx
import pytest
from fastapi.testclient import TestClient

from app.knowledge import GENERIC, TOPICS
from app.main import app

pytestmark = pytest.mark.ollama

MODEL = os.getenv("OLLAMA_TEST_MODEL", "qwen2.5:0.5b")
BASE_URL = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
PREDEFINED = ({t["explanation"] for t in TOPICS.values()} | {t["example"] for t in TOPICS.values()}
              | {GENERIC["example"]})


def _ollama_has_model() -> bool:
    try:
        tags = httpx.get(f"{BASE_URL}/api/tags", timeout=3).json()
    except (httpx.HTTPError, ValueError):
        return False
    return any(m.get("name", "").startswith(MODEL) for m in tags.get("models", []))


@pytest.fixture
def live_client(monkeypatch):
    if not _ollama_has_model():
        pytest.skip(f"Ollama is not running at {BASE_URL} or model {MODEL} is not pulled")
    monkeypatch.setenv("LLM_PROVIDER", "ollama")
    monkeypatch.setenv("OLLAMA_MODEL", MODEL)
    monkeypatch.setenv("OLLAMA_BASE_URL", BASE_URL)
    with TestClient(app) as client:
        yield client


def test_health_reports_ollama(live_client):
    body = live_client.get("/health").json()
    assert body["status"] == "ok" and body["llm_provider"] == "ollama" and body["model"] == MODEL


def test_ask_is_generated_by_the_model(live_client):
    response = live_client.post("/ask", json={"question": "What is photosynthesis? Explain with a simple example."})
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["mode"] == "ollama" and body["note"] is None and body["status"] == "success"
    assert body["explanation"] not in PREDEFINED and body["example"] not in PREDEFINED
    assert len(body["explanation"].split()) >= 8 and len(body["example"].split()) >= 5
    assert any(word in body["explanation"].lower() for word in ("light", "plant", "sun", "energy"))


def test_workflow_runs_end_to_end_with_the_model(live_client):
    response = live_client.post("/workflow", json={"question": "What is LangGraph?"})
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["mode"] == "ollama" and body["topic"] == "LangGraph"
    assert body["steps"][:3] == ["receive", "classify", "explain"] and body["steps"][-1] == "finalize"
    assert 1 <= body["attempts"] <= 2
    if body["status"] == "success":                     # generated by the model and validated
        assert body["note"] is None and body["example"] not in PREDEFINED and body["key_points"]
    else:                                               # a small model may still miss the format twice
        assert body["status"] == "fallback" and "Fallback" in body["note"]


def test_workflow_comparison_with_the_model(live_client):
    response = live_client.post("/workflow", json={"question": "LangChain vs LangSmith: what is the difference?"})
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["question_type"] == "comparison" and body["topic"] == "LangChain vs LangSmith"
    assert body["status"] in {"success", "fallback"} and body["steps"][-1] == "finalize"
